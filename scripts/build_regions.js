// Every populated 0.5° cell -> a UN M49 subregion, for the page's rope web (stacks join a
// regional cable, regional cables join a continental trunk).
//
//   node scripts/build_regions.js        (after build_data.py: it reads web/data/cells.js)
//
// Countries come from the vendored world-50m outlines (Natural Earth via world-atlas). A cell
// whose centre falls in no outline (coasts, small islands) takes the region of the nearest cell
// that does. Writes web/data/regions.js; see web/DATA.md.
"use strict";
const fs = require("fs"), path = require("path"), vm = require("vm");
const WEB = path.join(__dirname, "..", "web");
global.window = global;
global.atob = (s) => Buffer.from(s, "base64").toString("binary");
["js/fair-boot.js", "vendor/d3.min.js", "vendor/topojson-client.min.js", "vendor/world-50m.js", "data/cells.js"]
  .forEach((f) => vm.runInThisContext(fs.readFileSync(path.join(WEB, f), "utf8"), { filename: f }));
const d3 = global.d3, topojson = global.topojson;

// UN M49 subregions (ISO 3166 numeric ids as world-atlas spells them). Outlines without an id
// go by name. Antarctica (010) has nobody in it and is left out.
const CONTINENTS = ["Africa", "Asia", "Europe", "Latin America", "North America", "Oceania"];
const SUB = [
  ["Northern Africa", 0, "012 818 434 504 729 788 732"],
  ["Eastern Africa", 0, "108 174 262 232 231 404 450 454 480 508 646 690 706 728 800 834 894 716 086 260 Somaliland"],
  ["Middle Africa", 0, "024 120 140 148 178 180 226 266 678"],
  ["Southern Africa", 0, "072 748 426 516 710"],
  ["Western Africa", 0, "204 854 132 384 270 288 324 624 430 466 478 562 566 654 686 694 768"],
  ["Central Asia", 1, "398 417 762 795 860"],
  ["Eastern Asia", 1, "156 344 446 408 392 496 410 158"],
  ["South-eastern Asia", 1, "096 116 360 418 458 104 608 702 764 626 704"],
  ["Southern Asia", 1, "004 050 064 356 364 462 524 586 144 Siachen_Glacier"],
  ["Western Asia", 1, "051 031 048 196 268 368 376 400 414 422 512 634 682 275 760 792 784 887 N._Cyprus"],
  ["Eastern Europe", 2, "112 100 203 348 616 498 642 643 703 804"],
  ["Northern Europe", 2, "248 208 233 234 246 831 352 372 833 832 428 440 578 752 826"],
  ["Southern Europe", 2, "008 020 070 191 300 336 380 470 499 807 620 674 688 705 724 Kosovo"],
  ["Western Europe", 2, "040 056 250 276 438 442 492 528 756"],
  ["Caribbean", 3, "660 028 533 044 052 092 136 192 531 212 214 308 332 388 500 630 652 659 662 663 670 534 780 796 850"],
  ["Central America", 3, "084 188 222 320 340 484 558 591"],
  ["South America", 3, "032 068 076 152 170 218 238 328 600 604 239 740 858 862"],
  ["Northern America", 4, "060 124 304 666 840"],
  ["Australia and New Zealand", 5, "036 554 574 334 Indian_Ocean_Ter."],
  ["Melanesia", 5, "242 540 598 090 548"],
  ["Micronesia", 5, "316 296 584 583 520 580 585"],
  ["Polynesia", 5, "016 184 258 570 612 882 776 876"],
];
const subOf = {};
SUB.forEach(([, , ids], r) => ids.split(" ").forEach((k) => { subOf[k.replace(/_/g, " ")] = r; }));

const feats = topojson.feature(FAIR.world, FAIR.world.objects.countries).features;
const polys = [];
feats.forEach((f) => {
  const r = subOf[f.id] ?? subOf[f.properties.name];
  if (r === undefined) {
    if (f.id !== "010") console.warn("no subregion for", f.id, f.properties.name);
    return;
  }
  polys.push({ f, r, b: d3.geoBounds(f) });
});

const b = Buffer.from(FAIR.cells, "base64");
const ids = new Uint32Array(b.buffer, b.byteOffset, b.byteLength >> 2);
const N = ids.length, out = new Uint8Array(N).fill(255);
const lat = new Float64Array(N), lon = new Float64Array(N);
for (let i = 0; i < N; i++) {
  const row = Math.floor(ids[i] / 720), col = ids[i] - row * 720;
  lat[i] = 89.75 - 0.5 * row; lon[i] = -179.75 + 0.5 * col;
}
function inBox(bb, lo, la) {
  if (la < bb[0][1] - 0.01 || la > bb[1][1] + 0.01) return false;
  return bb[0][0] <= bb[1][0] ? lo >= bb[0][0] - 0.01 && lo <= bb[1][0] + 0.01 : lo >= bb[0][0] - 0.01 || lo <= bb[1][0] + 0.01;
}
for (let i = 0; i < N; i++) {
  for (const p of polys) {
    if (inBox(p.b, lon[i], lat[i]) && d3.geoContains(p.f, [lon[i], lat[i]])) { out[i] = p.r; break; }
  }
}
// Nearest assigned cell for the rest.
const D2R = Math.PI / 180, xyz = (i) => [Math.cos(lat[i] * D2R) * Math.cos(lon[i] * D2R), Math.cos(lat[i] * D2R) * Math.sin(lon[i] * D2R), Math.sin(lat[i] * D2R)];
const known = [], unknown = [];
for (let i = 0; i < N; i++) (out[i] === 255 ? unknown : known).push(i);
const KX = known.map(xyz);
unknown.forEach((i) => {
  const x = xyz(i);
  let best = -2, bi = -1;
  for (let j = 0; j < known.length; j++) {
    const k = KX[j], d = k[0] * x[0] + k[1] * x[1] + k[2] * x[2];
    if (d > best) { best = d; bi = j; }
  }
  out[i] = out[known[bi]];
});

const js = "// Generated by scripts/build_regions.js. Do not edit; see web/DATA.md.\n" +
  "FAIR.regions = {\n" +
  "  continents: " + JSON.stringify(CONTINENTS) + ",\n" +
  "  subregions: " + JSON.stringify(SUB.map(([n, c]) => ({ name: n, continent: c }))) + ",\n" +
  '  cell: "' + Buffer.from(out.buffer).toString("base64") + '",\n};\n';
fs.writeFileSync(path.join(WEB, "data", "regions.js"), js);
const counts = SUB.map(([n], r) => n + " " + out.filter((v) => v === r).length);
console.log(N + " cells, " + unknown.length + " by nearest neighbour\n" + counts.join("\n"));
